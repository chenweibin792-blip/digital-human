"""EdgeTTS adapter and reusable synthesis helpers.

All temporary audio is written below the workspace on E: and removed after it
has been decoded.  The helpers in this module are also used by the HTTP API so
the digital-human pipeline and the preview page share exactly the same rules.
"""

